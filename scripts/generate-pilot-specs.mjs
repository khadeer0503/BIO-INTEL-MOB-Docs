import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const pilots = JSON.parse(read('openapi/pilots.json'));
const shared = YAML.parse(read('openapi/wordpress.yaml'));
const failures = [];
const generatedHeader = '# Generated by npm run api:generate. Edit openapi/wordpress.yaml and openapi/pilots.json.\n';

if (pilots.length === 0 || pilots.filter(p => p.default).length !== 1) {
  throw new Error('Configure at least one pilot and exactly one default pilot.');
}
for (const field of ['name', 'slug', 'server']) {
  if (new Set(pilots.map(p => p[field])).size !== pilots.length) throw new Error(`Duplicate pilot ${field}.`);
}
for (const pilot of pilots) {
  if (!/^[a-z]+$/.test(pilot.slug) || pilot.server !== `https://${pilot.slug}.bio-intel-mob.eu/wp-json`) {
    throw new Error(`Invalid pilot configuration: ${pilot.name}`);
  }
}

function write(name, content) {
  const target = path.join(root, name);
  const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') : '';
  if (existing === content) return;
  if (check) { failures.push(name); return; }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
}

// Keep Rome first so existing links retain their default request destination.
shared.servers = [...pilots].sort((a, b) => Number(Boolean(b.default)) - Number(Boolean(a.default)))
  .map(p => ({ url: p.server, description: `${p.name} pilot` }));
write('openapi/wordpress.yaml', YAML.stringify(shared));

for (const pilot of pilots) {
  const spec = structuredClone(shared);
  spec.info.title = `BIO-INTEL-MOB: ${pilot.name} API`;
  spec.info.description = `Public dataset and REST discovery endpoints for the ${pilot.name} pilot. ` +
    'Generated from the shared BIO-INTEL-MOB contract. See the API overview for verification scope.';
  spec.servers = [{ url: pilot.server, description: `${pilot.name} pilot` }];
  spec.components.schemas.DatasetResponse.properties.city.example = pilot.name;
  spec.components.schemas.DatasetResponse.example.city = pilot.name;
  for (const operation of Object.values(spec.paths).flatMap(item => Object.values(item))) {
    if (operation && typeof operation === 'object' && operation.operationId) operation.operationId += pilot.name;
  }
  write(`openapi/pilots/${pilot.slug}.yaml`, generatedHeader + YAML.stringify(spec));
}

const docs = JSON.parse(read('docs.json'));
const apiTab = docs.navigation.tabs.find(t => t.tab === 'API Reference');
if (!apiTab) throw new Error('API Reference navigation tab is missing.');
delete apiTab.openapi;
delete apiTab.pages;
apiTab.groups = [
  { group: 'Start here', pages: ['api-reference/overview'] },
  { group: 'Shared API', openapi: { source: 'openapi/wordpress.yaml', directory: 'api-reference' } },
  ...pilots.map(p => ({
    group: p.name,
    openapi: { source: `openapi/pilots/${p.slug}.yaml`, directory: `api-reference/pilots/${p.slug}` },
  })),
];
write('docs.json', JSON.stringify(docs, null, 2) + '\n');

if (failures.length) {
  console.error(`Generated API files are out of date:\n${failures.join('\n')}\nRun npm run api:generate.`);
  process.exitCode = 1;
} else {
  console.log(`${check ? 'Checked' : 'Generated'} ${pilots.length} pilot specifications and API navigation.`);
}
